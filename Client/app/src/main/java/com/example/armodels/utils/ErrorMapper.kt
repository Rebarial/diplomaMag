fun <T> Result<T>.mapHttpError(): Result<T> {
    val ex = exceptionOrNull() ?: return this
    val code = when {
        ex is SocketTimeoutException -> "E.02"
        ex is IOException -> "E.01"
        ex is HttpException && ex.code() >= 500 -> "E.03"
        ex is HttpException -> ex.response()?.errorBody()?.string()?.trim() ?: "E.01"
        else -> return this
    }
    return Result.failure(Exception(code))
}
